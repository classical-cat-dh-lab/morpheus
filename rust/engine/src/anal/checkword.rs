#[no_mangle]
pub unsafe extern "C" fn checkword(mut Gkword: *mut gk_word) -> ::core::ffi::c_int {
    #[cfg(feature = "trace")] crate::trace::word("checkword:Gkword", Gkword as *const _);

    let mut rval: ::core::ffi::c_int = 0 as ::core::ffi::c_int;
    if has_morphflag(
        &raw mut (*Gkword).gs_stem.gs_morphflags as *mut MorphFlags,
        UNAUGMENTED,
    ) == 0
    {
        rval += checkindecl(Gkword);
    }
    if rval != 0 && quickflag != 0 {
        return rval;
    }
    if has_morphflag(
        &raw mut (*Gkword).gs_stem.gs_morphflags as *mut MorphFlags,
        UNAUGMENTED,
    ) == 0
    {
        rval += checknom(Gkword);
    }
    if rval != 0 && quickflag != 0 {
        return rval;
    }
    rval += checkverb(Gkword);
    return rval;
}
